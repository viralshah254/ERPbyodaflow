import * as React from "react";
import { cleanup, fireEvent, render, screen, waitFor } from "@testing-library/react";
import { afterEach, beforeEach, expect, it, vi } from "vitest";
const mocks = vi.hoisted(() => ({ post: vi.fn(), refresh: vi.fn(), close: vi.fn(), error: vi.fn() }));
vi.mock("sonner", () => ({ toast: { success: vi.fn(), error: mocks.error } }));
vi.mock("@/lib/api/finance", () => ({ fetchFinanceAccountsApi: async () => [{ id: "expense", code: "5000", name: "Synthetic expense", posts: true }] }));
vi.mock("@/lib/api/payments", () => ({ createApChequeApi: mocks.post, fetchApOpenItemsApi: vi.fn(), previewApSettlementApi: vi.fn(), searchApSupplierOptionsApi: vi.fn() }));
vi.mock("@/components/ui/async-searchable-select", () => ({ AsyncSearchableSelect: () => null }));
vi.mock("@/components/ui/searchable-select", () => ({ SearchableSelect: ({ placeholder, value, onValueChange, options }: { placeholder: string; value: string; onValueChange: (value: string) => void; options: Array<{ id: string; label: string }> }) => <select aria-label={placeholder} value={value} onChange={(event) => onValueChange(event.target.value)}><option value="">Select</option>{options.map((item) => <option key={item.id} value={item.id}>{item.label}</option>)}</select> }));
import { ApChequeBoxSheet } from "./ApChequeBoxSheet";
beforeEach(() => { vi.clearAllMocks(); mocks.post.mockResolvedValue({ id: "payment", number: "AP-TEST" }); mocks.refresh.mockRejectedValue(new Error("Refresh failed")); });
afterEach(cleanup);
it("removes a confirmed cheque and unlocks the form even if refreshing payments fails", async () => {
  render(<ApChequeBoxSheet open onOpenChange={mocks.close} bankAccounts={[{ id: "bank", name: "Synthetic bank" }]} onPosted={mocks.refresh} />);
  fireEvent.change(screen.getByLabelText("Bank account"), { target: { value: "bank" } });
  fireEvent.change(screen.getByPlaceholderText("Paid to 1"), { target: { value: "Synthetic payee" } });
  fireEvent.change(screen.getAllByPlaceholderText("Amount")[0], { target: { value: "25" } });
  fireEvent.change(screen.getAllByPlaceholderText("Cheque no.")[0], { target: { value: "TEST-1" } });
  fireEvent.click(screen.getAllByRole("button", { name: "No bill" })[0]);
  await waitFor(() => expect(screen.getByLabelText("Ledger account").querySelector('option[value="expense"]')).not.toBeNull());
  fireEvent.change(screen.getByLabelText("Ledger account"), { target: { value: "expense" } });
  fireEvent.click(screen.getByRole("button", { name: "Post cheques" }));
  await waitFor(() => expect(mocks.post).toHaveBeenCalledTimes(1));
  expect(mocks.post.mock.calls[0][0].clientRequestId).toBeTruthy();
  await waitFor(() => expect(mocks.close).toHaveBeenCalledWith(false));
  expect(screen.getByRole("button", { name: "Post cheques" })).toBeEnabled();
  expect(screen.queryByDisplayValue("TEST-1")).not.toBeInTheDocument();
  expect(mocks.error).toHaveBeenCalledWith(expect.stringContaining("Cheques were recorded"));
});
